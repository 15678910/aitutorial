// Main function to generate AI answer
export function generateAIAnswer(
  questionText: string,
  sectionTitle: string,
  chapterTitle: string,
  _courseSlug: string
): string {
  const searchText = `${questionText} ${sectionTitle} ${chapterTitle}`.toLowerCase()
  const questionLower = questionText.toLowerCase()

  // 1. Try to find a matching topic
  for (const topic of topicKnowledgeBase) {
    const topicMatch = topic.keywords.some(kw => searchText.includes(kw.toLowerCase()))
    if (!topicMatch) continue

    // 2. Try to find a matching answer pattern within the topic
    for (const answer of topic.answers) {
      if (answer.patterns.some(p => questionLower.includes(p))) {
        return answer.content
      }
    }

    // 3. Return topic's general answer
    return topic.generalAnswer
  }

  // 4. Try general pattern matching (topic-independent)
  for (const response of generalPatternResponses) {
    if (response.patterns.some(p => questionLower.includes(p))) {
      return response.content
    }
  }

  // 5. Ultimate fallback based on section context
  return `좋은 질문이에요! "${sectionTitle}" 주제에 대해 궁금한 점을 질문해주셨네요. 이 개념은 AI를 이해하는 데 중요한 기초가 되는 내용이에요. 위의 학습 자료를 다시 한번 꼼꼼히 읽어보고, 인터랙티브 실험도 직접 해보세요. 직접 경험해보면 이해가 훨씬 빨라질 거예요! 다른 친구들의 답변도 참고해보세요. 함께 배우면 더 즐거워요! 😊`
}
